@pytest.fixture(scope="module")
def matcher():
    index = load_schema_index()
    return CommandMatcher(index)


class TestPerformance:
    def test_p95_under_10ms(self, matcher):
        # Warmup
        for _ in range(10):
            for q in _QUERIES[:15]:
                matcher.match(q)

        # Timed runs across all queries (exact + multi-word fuzzy + unknown words)
        latencies: list[float] = []
        for q in _QUERIES:
            r = matcher.match(q)
            latencies.append(r.latency_ms)

        latencies.sort()
        n = len(latencies)
        p95_idx = int(n * 0.95)
        p95 = latencies[min(p95_idx, n - 1)]
        p99 = latencies[min(int(n * 0.99), n - 1)]
        mean = sum(latencies) / n

        print(f"\nPerformance: {n} queries, mean={mean:.3f}ms, p95={p95:.3f}ms, p99={p99:.3f}ms")

        assert p95 < 10.0, f"p95 latency {p95:.3f}ms exceeds 10ms threshold"
